// 多文化地域（クルビア・シエスタなど）における種族親和文化
const RACE_CULTURE_AFFINITY = {
  "ループス": "シラクーザ",
  "サンクタ": "ラテラーノ",
  "サルカズ": "カズデル",
  "コータス": "レム・ビリトン",
  "ドラコ": "ヴィクトリア",
  "アスラン": "ヴィクトリア",
  "クランタ": "カジミエーシュ",
  "フェリーン": "ヴィクトリア",
  "エラフィア": "サーミ",
  "ウルサス": "ウルサス",
  "ヒューマン": "クルビア"
};

function npcPoolFor(region, race = null) {
  const rng = typeof R === "function" ? R() : Math.random();
  // クルビアやシエスタ等の多文化移住地域では、親の種族文化を一定確率で反映（テキサス家のように出生国と文化がずれる例）
  const cosmopolitan = region === "クルビア" || region === "シエスタ";
  if (cosmopolitan && race && RACE_CULTURE_AFFINITY[race.n || race] && rng < 0.28) {
    const affinityRegion = RACE_CULTURE_AFFINITY[race.n || race];
    if (NPC_NAME_POOLS[affinityRegion]) return NPC_NAME_POOLS[affinityRegion];
  }
  let pool = NPC_NAME_POOLS[region] || NPC_NAME_POOLS["クルビア"];
  return pool.inherit ? NPC_NAME_POOLS[pool.inherit] : pool;
}

function npcNamePart(full, style) {
  if (!full) return "";
  if (style === "east") {
    const parts = String(full).split(" ");
    return parts.length > 1 ? parts.slice(1).join(" ") : parts[0];
  }
  return String(full).split("・")[0];
}

function npcFamilyPart(full, style) {
  if (!full) return null;
  if (style === "east") {
    const parts = String(full).split(" ");
    return parts.length > 1 ? parts[0] : null;
  }
  return String(full).split("・").slice(1).join("・") || null;
}

function nm_(sx, g, preferredFamily = null, options = {}) {
  const race = options.race || null;
  const pool = npcPoolFor(g?.n, race);
  const given = pick(sx === "男" ? pool.male : pool.female);
  const rng = typeof R === "function" ? R() : Math.random();

  // 単名（姓なし）の判定:
  // カズデル／サルカズ（単名文化）、ラテラーノ／サンクタ（洗礼名・修道名のみ）、
  // サーミ・イェラグの氏族個人名などを考慮。家名継承が指定されていない場合に判定。
  const isSarkaz = race?.n === "サルカズ" || (!race && g?.n === "カズデル");
  const isSancta = race?.n === "サンクタ" || (!race && g?.n === "ラテラーノ");
  const isSamiOrKjerag = g?.n === "サーミ" || g?.n === "イェラグ";

  const allowSingle = preferredFamily === false || (preferredFamily === null && (
    (pool.style === "single" || isSarkaz) ? rng < 0.70 :
    (isSancta && pool.singleAllowed) ? rng < 0.20 :
    (isSamiOrKjerag && pool.singleAllowed) ? rng < 0.22 : false
  ));

  if (allowSingle) {
    return given;
  }

  const family = preferredFamily || (pool.family && pool.family.length > 0 ? pick(pool.family) : null);
  if (!family) return given;

  return pool.style === "east" ? `${family} ${given}` : `${given}・${family}`;
}

function familyRelatedNames(s) {
  return [s?.nm, ...(s?.siblings || []).map(x => x?.nm), ...(s?.kids || []).map(x => x?.nm)].filter(Boolean);
}

function knownPersonNames(s) {
  return [
    s?.nm,
    s?.par?.fa?.nm,
    s?.par?.mo?.nm,
    ...(s?.siblings || []).map(person => person?.nm),
    ...(s?.siblings || []).flatMap(person => [
      person?.familyHousehold?.partner?.nm,
      ...(person?.familyHousehold?.children || []).map(child => child?.nm)
    ]),
    s?.sp?.nm,
    s?.romance?.nm,
    s?.romance?.name,
    ...(s?.kids || []).map(child => child?.nm),
    ...(s?.relationshipHistory || []).flatMap(person => [person?.nm, person?.name]),
    s?.friendContact?.nm,
    s?.neighborContact?.nm,
    ...(s?.care?.supportNetwork?.members || []).map(person => person?.nm),
    ...(s?.lifeRecord?.workRelationships || []).map(row => row.person?.nm)
  ].filter(name => typeof name === "string" && name.trim());
}

function nmUnique_(s, sx, g, extraNames = [], preferredFamily = null, options = {}) {
  const race = options.race || null;
  const pool = npcPoolFor(g?.n, race),
    style = pool.style;
  const used = [...knownPersonNames(s), ...extraNames].filter(
    name => typeof name === "string" && name.trim()
  );
  const all = new Set(used),
    reservedGiven = new Set(
      [...familyRelatedNames(s), ...extraNames].map(name => npcNamePart(name, style)).filter(Boolean)
    );
  for (let i = 0; i < 180; i++) {
    const candidate = nm_(sx, g, preferredFamily, options);
    const candidateGiven = npcNamePart(candidate, style);
    if (!all.has(candidate) && !reservedGiven.has(candidateGiven)) return candidate;
  }

  // 単純な番号付けではなく、候補中の未使用の姓名を総当たりして重複を避ける。
  const givenList = sx === "男" ? pool.male : pool.female;
  const familyCandidates = preferredFamily
    ? [preferredFamily]
    : pool.family && pool.family.length > 0
    ? pool.family
    : [null];

  for (const given of givenList) {
    if (reservedGiven.has(given)) continue;
    for (const family of familyCandidates) {
      let candidate;
      if (!family) {
        candidate = given;
      } else if (style === "east") {
        candidate = `${family} ${given}`;
      } else {
        candidate = `${given}・${family}`;
      }
      if (!all.has(candidate)) return candidate;
    }
  }

  // 大量生成でも安易な番号サフィックス（・2等）を付与せず、同名を受け入れる（設計書指針）。
  return nm_(sx, g, preferredFamily, options);
}

const pickRaceFor = g => {
  const mod = RACE_AFF[g.n] || {};
  return wp(RACE.map(r => ({ r, w: (r.w || 1) * (mod[r.n] || 1) }))).r;
};

const pickHouseholdMateRace = (g, anchor) => {
  const cosmopolitan = new Set(["炎国", "クルビア", "龍門", "ボリバル", "シエスタ", "ヴィクトリア"]);
  const sameRaceChance = cosmopolitan.has(g.n) ? 0.68 : 0.86;
  if (R() < sameRaceChance) return anchor;
  const alternatives = RACE.filter(r => r.n !== anchor.n).map(r => ({
    r,
    w: (r.w || 1) * (RACE_AFF[g.n]?.[r.n] || 1)
  }));
  return alternatives.length ? wp(alternatives).r : anchor;
};

const pickChildRace = (parents, g) => {
  const races = (parents || [])
    .map(r => (typeof r === "string" ? RACE.find(x => x.n === r) : r))
    .filter(Boolean);
  return races.length > 1 ? pick(races) : races[0] || pickRaceFor(g);
};
