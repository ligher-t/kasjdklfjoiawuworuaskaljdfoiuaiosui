/* P12: observed nonformal learning, independent from school attendance and
 * formal qualifications. Rates are game-model annual reference values. */
const EDUCATION_NONFORMAL_MODES=Object.freeze({
  "home-literacy":{axes:[5,3,0,0],subjects:["basic_literacy","practical_numeracy"]},
  "self-directed":{axes:[2,5,1,2],subjects:["academic_knowledge"]},
  "neighborhood-literacy":{axes:[8,4,0,3],subjects:["basic_literacy","practical_numeracy"]},
  "roving-tutor":{axes:[7,5,0,5],subjects:["basic_literacy","language","arithmetic"]},
  "temporary-community-class":{axes:[6,4,1,3],subjects:["basic_literacy","community_knowledge"]},
  "clan-tradition":{axes:[1,3,8,8],subjects:["terrain","ecology","oral_tradition"]},
  "dojo-or-guild":{axes:[1,3,8,3],subjects:["craft","physical_practice"]},
  "religious-community":{axes:[5,4,3,4],subjects:["literacy","ritual_knowledge"]},
  "workshop-apprenticeship":{axes:[3,4,9,3],subjects:["manufacturing","repair"]},
  "evening-literacy":{axes:[9,4,0,5],subjects:["basic_literacy","documentation"]},
  "evening-vocational":{axes:[3,5,7,4],subjects:["technical","office"]},
  correspondence:{axes:[5,5,2,5],subjects:["academic_knowledge","language"]},
  "corporate-training":{axes:[2,4,9,4],subjects:["technical","safety"]},
  "rhodes-onboard":{axes:[6,6,4,7],subjects:["academic_knowledge","medical_safety","language"]},
  "community-health-training":{axes:[2,4,7,4],subjects:["first_aid","medical_safety"]},
  "exam-self-preparation":{axes:[3,6,1,4],subjects:["test_preparation","formal_register"]}
});
const EDUCATION_NONFORMAL_AXES=["literacy","knowledge","practicalSkill","language"];
const EDUCATION_NONFORMAL_CAPS=Object.freeze({
  literacy:12,knowledge:10,practicalSkill:15,language:12
});
function educationInformalProvider(s,providerId) {
  return s.world?.educationWorld?.informalProviders?.[providerId]||null;
}
function educationRegisterInformalProvider(s,{providerId,personId=null,organizationId=null,
  kind,areaId=null,mobileRouteId=null,languageId=null,
  activeFrom,activeTo=null,subjectIds,evidenceRef}={}) {
  const world=s?.world?.educationWorld;
  if(!world||!providerId||!evidenceRef||!kind||!Array.isArray(subjectIds)||
     !subjectIds.length||!activeFrom||!Number.isInteger(activeFrom.year)||
     activeFrom.year>s.year||areaId&&!world.areas?.[areaId]||
     !personId&&!organizationId||
     (activeTo && activeTo.year*12+(activeTo.month||0)<
       activeFrom.year*12+(activeFrom.month||0)))
    throw Error("証拠を持つ学校外指導者・実在場所・期間が不足");
  // A provider is an explicitly witnessed person or organization, not
  // another school generated by the school-presence probability.
  world.informalProviders ||= {};
  const next={
    id:providerId,providerId,personId,organizationId,kind,
    areaId,mobileRouteId,languageId,subjectIds:[...subjectIds],
    activeFrom:{...activeFrom},activeTo:activeTo?{...activeTo}:null,
    sourceKind:"observed-provider",evidenceRef,status:"active"
  };
  if(world.informalProviders[providerId]){
    if(JSON.stringify(world.informalProviders[providerId])!==JSON.stringify(next))
      throw Error("学校外指導者の同一IDに矛盾");
    return world.informalProviders[providerId];
  }
  world.informalProviders[providerId]=next;
  return next;
}
function educationLearningPathList(s,personId,create=false) {
  if(personId==="protagonist"){
    if(create)s.learningPaths ||= [];
    return s.learningPaths||[];
  }
  const dependent=educationDependentEntry(s,personId,create);
  return dependent?.learningPaths||null;
}
function educationLearningPath(s,personId,pathId) {
  return educationLearningPathList(s,personId)?.find(x=>x.pathId===pathId)||null;
}
function educationOpenLearningPath(s,{personId="protagonist",modeId,providerId,
  siteRef,subjectIds,sourceEventId,languageId=null,
  languageMode=null,quality=0.8}={}) {
  const mode=EDUCATION_NONFORMAL_MODES[modeId],
    self=["self-directed","exam-self-preparation"].includes(modeId),
    provider=educationInformalProvider(s,providerId),
    list=educationLearningPathList(s,personId,true);
  if(s.dead||!mode||!list||!sourceEventId||!Number.isFinite(quality)||
     quality<0.4||quality>1||!siteRef||!siteRef.region||
     !Array.isArray(subjectIds)||!subjectIds.length||
     subjectIds.some(x=>!mode.subjects.includes(x)) ||
     (!self&&!provider)||
     (provider && provider.status!=="active")||
     (self&&providerId!=="self"&&(!provider||provider.kind!=="self"))||
     modeId==="rhodes-onboard"&&!((s.fl?.rhodes===1)||
       [28,29,30,31,32,33,34].includes(s.job))||
     modeId==="corporate-training"&&s.job<=0)
    throw Error("非正規学習の指導者・受講者・場所・科目が未確認");
  const pathId=["learn",personId,modeId,providerId,sourceEventId].join(":");
  const old=list.find(x=>x.pathId===pathId);
  if(old)return old;
  const row={
    pathId,personId,modeId,
    providerRef:provider?{
      kind:provider.kind,personId:provider.personId,
      organizationId:provider.organizationId,
      evidenceBasis:provider.evidenceRef}:{
        kind:"self",personId, evidenceBasis:sourceEventId
      },
    providerId:providerId||"self",
    siteRef:{...siteRef},subjectIds:[...subjectIds],
    startedAt:{year:s.year,month:s.mo??0},endedAt:null,
    status:"active",enrollmentBasis:"observed-agreement",
    participation:[],evidenceIds:[],sourceEventIds:[sourceEventId],
    lastReviewedPeriod:null,knowledgeVisibility:personId==="protagonist"?
      "self-known":"dependent-unverified",
    quality,languageId,languageMode
  };
  list.push(row);return row;
}
function educationNonformalProviderActive(s,path,year,month) {
  if(path.providerId==="self")return true;
  const provider=educationInformalProvider(s,path.providerId);
  if(!provider||provider.status!=="active")return false;
  const at=year*12+month,
    from=provider.activeFrom.year*12+(provider.activeFrom.month||0),
    to=provider.activeTo?
      provider.activeTo.year*12+(provider.activeTo.month||12):Infinity;
  if(at<from||at>to)return false;
  if(provider.areaId && provider.areaId!==path.siteRef.areaId)return false;
  return !provider.languageId || !path.languageId ||
    provider.languageId===path.languageId;
}
function educationCompetenceGain(s,personId,path,period,attendance,quality,
  originEvidenceId,alreadyApplied) {
  if(alreadyApplied)return [];
  s.learningCompetenceEffects ||= {version:1,items:{},annualTotals:{}};
  const ledger=s.learningCompetenceEffects,mode=EDUCATION_NONFORMAL_MODES[path.modeId],
    dependent=personId==="protagonist"?null:educationDependentEntry(s,personId,true);
  const target=dependent?(dependent.competences||={literacy:0,knowledge:0,
    practicalSkill:0,language:0}):null,
    rows=[];
  for(let i=0;i<EDUCATION_NONFORMAL_AXES.length;i++){
    const axis=EDUCATION_NONFORMAL_AXES[i],base=mode.axes[i];
    if(!base)continue;
    if(axis==="language" && (!path.languageId||!path.languageMode))continue;
    const appliedId=[personId,path.pathId,period,axis,originEvidenceId].join("|");
    if(ledger.items[appliedId])continue;
    const key=personId+":"+period.slice(0,4)+":"+axis+
      (axis==="language"?":"+path.languageId+":"+path.languageMode:"");
    const used=ledger.annualTotals[key]||0,
      available=Math.max(0,EDUCATION_NONFORMAL_CAPS[axis]-used);
    if(!available)continue;
    const skill=dependent?target[axis]||0:
      axis==="literacy"?(s.socialLearning?.literacy??0):
      axis==="knowledge"?(s.k||0):
      axis==="language"?getLanguageSkill(s,path.languageId,path.languageMode):
      (s.learningPracticalSkill||0);
    const delta=Math.min(available,base*attendance*quality/12*
      Math.max(0,1-0.5*Math.max(0,Math.min(100,skill))/100));
    if(delta<=0)continue;
    if(dependent)target[axis]=Math.min(100,(target[axis]||0)+delta);
    else if(axis==="literacy"){
      const social=socialModel(s);
      social.literacy=Math.min(100,(social.literacy??0)+delta);
    }else if(axis==="knowledge")s.k=Math.min(100,(s.k||0)+delta);
    else if(axis==="practicalSkill"){
      s.learningPracticalSkill=Math.min(100,(s.learningPracticalSkill||0)+delta);
      const record=ensureLifeRecord(s),skillId="nonformal:"+path.subjectIds[0];
      let entry=record.skills.find(x=>x.id===skillId);
      if(!entry){
        entry={id:skillId,level:0,source:"nonformal-evidence",history:[]};
        record.skills.push(entry);
      }
      entry.level=Math.min(100,entry.level+delta);
      entry.history.push({year:s.year,sourceEventId:originEvidenceId,delta});
    }else if(axis==="language"){
      applyLanguageAction(s,{type:"learn",languageId:path.languageId,
        mode:path.languageMode,amount:delta});
    }
    ledger.annualTotals[key]=used+delta;
    const item={
      effectId:appliedId,evidenceId:originEvidenceId,personId,domainId:axis,
      delta,appliedPeriod:period,originEventId:originEvidenceId,
      appliedTo:axis,dedupKey:appliedId
    };
    ledger.items[appliedId]=item;rows.push(item);
  }
  return rows;
}
function educationRecordLearningParticipation(s,{personId="protagonist",pathId,
  year=s.year,month=s.mo,attendedSessions,totalSessions,
  evidenceRef,originFormalEvidenceId=null,alreadyApplied=false}={}) {
  const path=educationLearningPath(s,personId,pathId);
  if(s.dead||!path||path.status!=="active"||!evidenceRef||
     !Number.isInteger(year)||!Number.isInteger(month)||month<1||month>12||
     year>s.year||year===s.year&&month>(s.mo??0)||
     !Number.isInteger(totalSessions)||totalSessions<1||
     !Number.isInteger(attendedSessions)||attendedSessions<0||
     attendedSessions>totalSessions||
     !educationNonformalProviderActive(s,path,year,month))
    throw Error("学校外学習の実参加・講師の活動期間が不正");
  if(originFormalEvidenceId && Object.values(s.educationAttendance?.enrollments||{})
    .some(yrs=>Object.values(yrs).some(months=>
      Object.values(months).some(row=>Object.values(row.segments||{})
        .some(segment=>segment.evidenceRef===originFormalEvidenceId)))))
    throw Error("正式履修と同じ受講証拠に二重の教育効果");
  if(personId!=="protagonist"){
    const child=educationDependentEntry(s,personId);
    if(!child.consents.some(x=>x.purpose==="informal-learning"&&x.status==="approved"))
      throw Error("子本人の学びと保護者の承諾が未確認");
  }
  const key=year+"-"+String(month).padStart(2,"0"),
    existing=path.participation.find(x=>x.periodKey===key);
  if(existing){
    if(existing.evidenceIds.includes(evidenceRef))return existing;
    throw Error("同月の受講実績を別IDで二重に数えられない");
  }
  const fraction=attendedSessions/totalSessions,
    item={
      periodKey:key,pathId,personId,totalSessions,attendedSessions,
      effectiveAttendanceFraction:fraction,teacherPresent:path.providerId!=="self",
      workshopAvailable:true,supportIds:[],disruptionReasons:[],
      evidenceIds:[evidenceRef],sourceKind:"confirmed-event-observation",
      quality:path.quality
    };
  path.participation.push(item);path.evidenceIds.push(evidenceRef);
  path.lastReviewedPeriod=key;
  educationCompetenceGain(s,personId,path,key,fraction,path.quality,
    evidenceRef,alreadyApplied);
  return item;
}
function educationCloseLearningPath(s,personId,pathId,status,evidenceRef) {
  const path=educationLearningPath(s,personId,pathId);
  if(!path||!["completed_noncredential","temporarily_inaccessible",
    "interrupted","cancelled"].includes(status)||!evidenceRef)
    throw Error("学校外学習の終了・中断記録が不正");
  if(path.status===status)return path;
  path.status=status;
  path.endedAt={year:s.year,month:s.mo??0};
  path.sourceEventIds.push(evidenceRef);
  return path;
}
function educationNonformalRecognition(s,{personId="protagonist",applicationId,
  pathId,authorityId,ruleId,targetJurisdiction,targetStageOrRole,
  outcome,assessmentEvidenceId,sourceEventId,recognitionKind,
  effectiveFrom}={}) {
  const path=educationLearningPath(s,personId,pathId),
    authority=s.world?.educationWorld?.institutions?.[authorityId],
    rule=authority?.nonformalRecognitionRules?.[ruleId],
    accepted=["accepted","partially_accepted"].includes(outcome);
  if(!path||!applicationId||!authority||!rule||
     !targetJurisdiction||!targetStageOrRole||!sourceEventId||
     !assessmentEvidenceId||!effectiveFrom||
     !["entry_eligibility","partial_course_credit","skill_certificate",
       "occupational_registration"].includes(recognitionKind)||
     rule.kind!==recognitionKind||rule.targetStageOrRole!==targetStageOrRole||
     rule.jurisdiction!==targetJurisdiction ||
     !rule.approved||!rule.sourceRef||
     !["accepted","partially_accepted","refused","withdrawn"].includes(outcome))
    throw Error("学校外の能力を正式に認定する機関・規則・審査が未確認");
  const store=personId==="protagonist" ?
    (s.educationRecord||(s.educationRecord={
      version:1,enrollments:[],awards:[]})) :
    educationDependentEntry(s,personId,true);
  store.recognitionApplications ||= {};
  const existing=store.recognitionApplications[applicationId];
  if(existing)return existing;
  const item={
    applicationId,personId,pathId,targetAuthorityId:authorityId,
    targetJurisdiction,targetRecognitionRuleId:ruleId,
    submittedEvidenceIds:[...path.evidenceIds],
    requiredAssessmentIds:[assessmentEvidenceId],
    applicationStatus:outcome,
    submittedAt:{...effectiveFrom},decidedAt:{year:s.year,month:s.mo??0},
    outcomeType:accepted?recognitionKind:"none",
    decisionReason:sourceEventId
  };
  store.recognitionApplications[applicationId]=item;
  if(accepted){
    store.recognitions ||= [];
    store.recognitions.push({
      recognitionId:"recognition:"+applicationId,
      personId,applicationId,authorityId,ruleId,
      targetStageOrRole,recognitionKind,
      scope:targetJurisdiction,
      validFrom:{...effectiveFrom},validUntil:rule.validUntil||null,
      sourceEvidenceIds:[...path.evidenceIds,assessmentEvidenceId],
      sourceEventId
    });
  }
  return item;
}
function educationNonformalInvariants(s) {
  const errs=[],seen=new Set();
  for(const [personId,list] of [
    ["protagonist",s.learningPaths||[]],
    ...Object.entries(s.dependentEducation||{}).map(([id,entry])=>
      [id,entry.learningPaths||[]])]){
    for(const p of list){
      if(seen.has(p.pathId)||p.personId!==personId||
         !EDUCATION_NONFORMAL_MODES[p.modeId]||
         !["intended","active","temporarily_inaccessible","interrupted",
           "completed_noncredential","cancelled"].includes(p.status)||
         p.participation.some(x=>x.personId!==personId||
           x.effectiveAttendanceFraction<0||x.effectiveAttendanceFraction>1))
        errs.push("学校外学習の人物ID・期間・実績に不整合");
      seen.add(p.pathId);
    }
  }
  if(Object.values(s.learningCompetenceEffects?.annualTotals||{})
    .some(n=>!Number.isFinite(n)||n<0||n>15.00001))
    errs.push("学校外学習の年間技能・知識上限に違反");
  return errs;
}
