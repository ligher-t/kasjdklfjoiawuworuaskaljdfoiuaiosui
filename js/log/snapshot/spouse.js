function traceSpouse(s, services) {
  return {
    spouse: s.sp
      ? {
          id: s.sp.id,
          name: s.sp.nm,
          birthYear: s.sp.by || null,
          alive: !s.sp.d,
          deathYear: s.sp.deathYear ?? null,
          deathCause: s.sp.deathCause || null,
          deathNoticePending: !!s.sp.deathNoticePending,
          deathNoticeAvailableYear: s.sp.deathNoticeAvailableYear ?? null,
          deathNoticeChannel: s.sp.deathNoticeChannel || null,
          deathNoticeHistory: (s.sp.deathNoticeHistory || []).map(row => ({ ...row })),
          mortalityCheckedYear: s.sp.mortalityCheckedYear ?? null,
          infected: !!s.sp.inf,
          infectionKnown: !!s.sp.inf && !s.sp.infHidden,
          disclosureBoundary: s.sp.disclosureBoundary || null,
          disclosureBoundarySinceYear: s.sp.disclosureBoundarySinceYear ?? null,
          disclosureReviewYear: s.sp.disclosureReviewYear ?? null,
          disclosureBoundaryHistory: s.sp.disclosureBoundaryHistory || [],
          treatment: !!s.sp.tx,
          health: Number.isFinite(s.sp.health) ? s.sp.health : null,
          healthBasis: s.sp.healthBasis || null,
          healthUpdatedYear: s.sp.healthUpdatedYear ?? null,
          healthHistory: s.sp.healthHistory || [],
          healthPlan: s.sp.healthPlan || null,
          healthReviewHistory: s.sp.healthReviewHistory || [],
          healthNoticePending: !!s.sp.healthNoticePending,
          relationship: s.sp.marriageType || "married",
          householdArrangement: s.sp.householdArrangement || "unrecorded",
          residenceRegion: s.sp.residenceRegion || s.res.n,
          sharesHousehold: typeof s.sp.sharesHousehold === "boolean" ? s.sp.sharesHousehold : null,
          cohabiting: services.spouseLivesWithProtagonist(s),
          knownResidenceRegion: services.spouseKnownResidenceRegion(s).n,
          regionalServices: services.spouseRegionalServiceContext(s),
          residenceKnownYear: s.sp.residenceKnownYear ?? null,
          independentMoveReviewYear: s.sp.independentMoveReviewYear ?? null,
          residenceMoveNotice: s.sp.residenceMoveNotice ? { ...s.sp.residenceMoveNotice } : null,
          residenceNoticeHistory: (s.sp.residenceNoticeHistory || []).map(row => ({ ...row })),
          residenceHistory: (s.sp.residenceHistory || []).map(row => ({ ...row })),
          residenceMovePending: s.sp.residenceMovePending ? { ...s.sp.residenceMovePending } : null,
          livingApart: !services.spouseLivesWithProtagonist(s),
          visitCount: s.sp.visitCount || 0,
          visitTotal: s.sp.visitTotal || 0,
          visitHistory: (s.sp.visitHistory || []).map(row => ({ ...row })),
          separateContact: s.sp.separateContact || "unrecorded",
          housingPlan: s.sp.housingPlan || "unrecorded",
          housingPlanHistory: (s.sp.housingPlanHistory || []).map(row => ({ ...row })),
          annualHousingCost: services.spouseIndependentHousingExpense(s),
          annualSeparateContactCost: services.spouseSeparateContactAnnualCost(s),
          separateContactPaidTotal: s.sp.separateContactPaidTotal || 0,
          separateContactPaidYear: s.sp.separateContactPaidYear || null,
          separateContactPaidAmount: s.sp.separateContactPaidAmount || 0,
          separateContactHistory: (s.sp.separateContactHistory || []).map(row => ({ ...row })),
          separateSupportPlan: s.sp.separateSupportPlan || "unrecorded",
          separateLifeReviewYear: s.sp.separateLifeReviewYear ?? null,
          separateLifeReviewHistory: (s.sp.separateLifeReviewHistory || []).map(row => ({ ...row })),
          separateSupportPaidTotal: s.sp.separateSupportPaidTotal || 0,
          separateSupportPaidYear: s.sp.separateSupportPaidYear || null,
          separateSupportPaidAmount: s.sp.separateSupportPaidAmount || 0,
          separateSupportHistory: (s.sp.separateSupportHistory || []).map(row => ({ ...row })),
          annualSeparateSupport: services.spouseSeparateSupportCost(s),
          annualHouseholdContribution: services.spouseHouseholdIncome(s),
          personalFinance: s.sp.personalFinance
            ? {
                ...s.sp.personalFinance,
                history: (s.sp.personalFinance.history || []).map(row => ({ ...row })),
                supportReceipts: (s.sp.personalFinance.supportReceipts || []).map(row => ({ ...row }))
              }
            : null,
          jobId: s.sp.j ?? null,
          employmentStatus: services.spouseEmploymentStatus(s.sp),
          unemployedSinceYear: s.sp.unemployedSinceYear ?? null,
          unemploymentSupportPending: !!s.sp.unemploymentSupportPending,
          workReviewYear: s.sp.workReviewYear ?? null,
          workHistory: (s.sp.workHistory || []).map(row => ({ ...row })),
          employmentHistory: (s.sp.employmentHistory || []).map(row => ({ ...row })),
          employmentSupportHistory: (s.sp.employmentSupportHistory || []).map(row => ({ ...row })),
          workPreference: s.sp.workPreference || "unrecorded",
          workPreferenceReviewYear: s.sp.workPreferenceReviewYear ?? null,
          workPreferenceReviewPending: !!s.sp.workPreferenceReviewPending,
          workPreferenceReviewCause: s.sp.workPreferenceReviewCause || null,
          workPreferenceHistory: (s.sp.workPreferenceHistory || []).map(row => ({ ...row })),
          employmentMarket: services.spouseEmploymentMarketContext(s.sp, s.res.n)
        }
      : null
  };
}
