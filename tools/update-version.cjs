'use strict';
const fs = require('node:fs');
const path = require('node:path');
const {createHash} = require('node:crypto');
const {scriptFiles} = require('./runtime.cjs');
const root = path.resolve(__dirname, '..');
const canonicalSource = source => source.replace(/\r\n?/g,'\n');
function revision(rootDir = root) {
  const hash = createHash('sha256');
  for (const file of scriptFiles(rootDir).filter(file => file !== 'js/version.js')) {
    hash.update(file + '\0');
    hash.update(canonicalSource(fs.readFileSync(path.join(rootDir, file),'utf8')));
  }
  return hash.digest('hex');
}
if (require.main === module) {
  if(process.argv.includes('--check')) {
    const expected=revision(),current=fs.readFileSync(path.join(root,'js/version.js'),'utf8');
    if(!current.includes('const ENGINE_REVISION = '+JSON.stringify(expected)+';')) {
      console.error('Stale engine revision: run node tools/update-version.cjs');process.exitCode=1;
    } else console.log('Engine revision matches canonical runtime source');
  } else {
  fs.writeFileSync(path.join(root, 'js/version.js'),
    '// Generated by node tools/update-version.cjs; keep with the runtime files.\n' +
    `const ENGINE_REVISION = "${revision()}";\n`);
  console.log('Updated js/version.js');
  }
}
module.exports = {revision,canonicalSource};
